import { readFileSync, writeFileSync } from 'node:fs';
import { parseRoutes } from './route-inventory.mjs';
const legalSource = readFileSync(new URL('../../src/pages/legal/GenericLegalPage.tsx', import.meta.url), 'utf8');
const paths = [...new Set([
  ...parseRoutes().map(route => route.path).filter(path => path !== '*' && path !== '/legal/*' && path !== '/:countrySlug' && !path.startsWith('/dev/')),
  ...[...legalSource.matchAll(/"(\/legal\/[^"\s]+)"\s*:/g)].map(match => match[1]),
])].sort();
const output = '// Generated by node scripts/seo/generate-worker-routes.mjs. Do not edit.\nexport const appRoutes = ' + JSON.stringify(paths, null, 2) + ' as const;\n';
const target = new URL('../../cloudflare/app-routes.generated.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) throw new Error('Worker routes are stale. Run node scripts/seo/generate-worker-routes.mjs');
} else writeFileSync(target, output);
console.log(`Worker route manifest: ${paths.length} routes`);
